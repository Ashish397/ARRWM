def read_frames(path):
    cap = cv2.VideoCapture(path)
    fr = []
    while True:
        ok, f = cap.read()
        if not ok:
            break
        fr.append(cv2.cvtColor(f, cv2.COLOR_BGR2RGB))
    cap.release()
    return np.stack(fr)


def make_sxs_pack(frames_a, frames_b, pack):
    """Side-by-side composites: A left, B right, labeled header, temporal order."""
    n = min(len(frames_a), len(frames_b))
    base = pack.replace("+diff", "")
    W_, H_ = (640, 352) if base.startswith("hi") else (448, 240)
    if base in ("uniform16", "hi16"):
        idx = np.linspace(0, n - 1, 16).round().astype(int)
    elif base in ("uniform24", "hi24"):
        idx = np.linspace(0, n - 1, 24).round().astype(int)
    else:
        idx = np.linspace(0, n - 1, 32).round().astype(int)
    def compose(a_img, b_img, label=None):
        div = np.full((a_img.shape[0], 8, 3), 255, np.uint8)
        comp = np.concatenate([a_img, div, b_img], axis=1)
        header = np.full((28, comp.shape[1], 3), 32, np.uint8)
        cv2.putText(header, label or "A", (170 if label else 200, 22), cv2.FONT_HERSHEY_SIMPLEX, 0.7, (255, 255, 255), 2)
        if not label:
            cv2.putText(header, "B", (660, 22), cv2.FONT_HERSHEY_SIMPLEX, 0.8, (255, 255, 255), 2)
        else:
            cv2.putText(header, label, (560, 22), cv2.FONT_HERSHEY_SIMPLEX, 0.7, (255, 255, 255), 2)
        return Image.fromarray(np.concatenate([header, comp], axis=0))

    ims = []
    for i in idx:
        a = cv2.resize(frames_a[i], (W_, H_))
        b = cv2.resize(frames_b[i], (W_, H_))
        ims.append(compose(a, b))
    if pack.endswith("+diff"):
        n2 = min(len(frames_a), len(frames_b))
        for t in [n2 // 2, 3 * n2 // 4, n2 - 2]:
            da = cv2.resize(np.abs(frames_a[t + 1].astype(np.int16) - frames_a[t].astype(np.int16)).astype(np.uint8) * 3, (W_, H_))
            db = cv2.resize(np.abs(frames_b[t + 1].astype(np.int16) - frames_b[t].astype(np.int16)).astype(np.uint8) * 3, (W_, H_))
            ims.append(compose(np.clip(da, 0, 255), np.clip(db, 0, 255), label="A CHANGE MAP  /  B CHANGE MAP"))
    return ims


def make_pack(frames, pack):
    n = len(frames)
    if pack == "uniform32":
        idx = np.linspace(0, n - 1, 32).round().astype(int)
    elif pack == "uniform16":
        idx = np.linspace(0, n - 1, 16).round().astype(int)
    elif pack == "late48":
        idx = np.unique(np.concatenate([
            np.linspace(0, n - 1, 24).round().astype(int),
            np.linspace(2 * n // 3, n - 1, 24).round().astype(int)]))
    else:
        raise ValueError(pack)
    return [Image.fromarray(cv2.resize(frames[i], (448, 240))) for i in idx]


class MiniCPM:
    name = "minicpm45"

    def __init__(self):
        from transformers import AutoModel, AutoTokenizer
        self.model = AutoModel.from_pretrained("openbmb/MiniCPM-V-4_5", trust_remote_code=True,
                                               attn_implementation="sdpa", torch_dtype=torch.bfloat16).eval().cuda()
        self.tok = AutoTokenizer.from_pretrained("openbmb/MiniCPM-V-4_5", trust_remote_code=True)

    def judge_single(self, ims, prompt_text):
        msgs = [{"role": "user", "content": list(ims) + [prompt_text]}]
        with torch.no_grad():
            return self.model.chat(msgs=msgs, image=None, tokenizer=self.tok,
                                   use_image_id=False, max_slice_nums=1,
                                   sampling=False, max_new_tokens=300)

    def judge(self, ims_a, ims_b, prompt_text):
        content = (["Video A, frames in temporal order:"] + ims_a +
                   ["Video B, frames in temporal order:"] + ims_b + [prompt_text])
        msgs = [{"role": "user", "content": content}]
        with torch.no_grad():
            ans = self.model.chat(msgs=msgs, image=None, tokenizer=self.tok,
                                  use_image_id=False, max_slice_nums=1,
                                  sampling=False, max_new_tokens=300)
        return ans


def parse_verdict(text):
    m = re.findall(r"\{[^{}]*\}", text, re.S)
    for chunk in reversed(m):
        try:
            d = json.loads(chunk.replace("'", '"'))
            if "overall" in d:
                return d
        except json.JSONDecodeError:
            continue
    # fallback: last standalone A/B/T mention
    m2 = re.findall(r'"?overall"?\s*[:=]\s*"?([ABT])"?', text)
    if m2:
        return {"overall": m2[-1]}
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--prompt", default="pairwise_decomposed", choices=list(PROMPTS))
    ap.add_argument("--pack", default="uniform32")
    ap.add_argument("--model", default="minicpm")
    ap.add_argument("--grids", default=None, help="comma list; default = all grids in gt.json")
    ap.add_argument("--layout", default="seq", choices=["seq", "sxs"])
    args = ap.parse_args()

    gt = json.load(open(os.path.join(HERE, "gt.json")))["grids"]
    grids = args.grids.split(",") if args.grids else list(gt.keys())

    judge = MiniCPM()
    prompt_text = PROMPTS[args.prompt]
    if args.layout == "sxs" and prompt_text.startswith(RULES):
        prompt_text = RULES_SXS + prompt_text[len(RULES):]
    prompt_tag = args.prompt + ("_sxs" if args.layout == "sxs" else "")

    done = set()
    if os.path.exists(OUT):
        for line in open(OUT):
            r = json.loads(line)
            done.add((r["model"], r["prompt"], r["pack"], r["grid"], r["a"], r["b"]))

    fout = open(OUT, "a")
    for grid in grids:
        variants = list(gt[grid].keys())
        # cache frames / packs
        raw = {}
        packs = {}
        for v in variants:
            fp = os.path.join(TILE_DIR, f"{grid}__{v}.mp4")
            if not os.path.exists(fp):
                fp = os.path.join(HERE, "tiles_new", f"{grid}__{v}.mp4")
            raw[v] = read_frames(fp)
            if args.layout == "seq":
                packs[v] = make_pack(raw[v], args.pack)
        for va, vb in itertools.combinations(sorted(variants), 2):
            for a, b in [(va, vb), (vb, va)]:  # both orders
                key = (judge.name, prompt_tag, args.pack, grid, a, b)
                if key in done:
                    continue
                try:
                    if args.layout == "sxs":
                        ims = make_sxs_pack(raw[a], raw[b], args.pack)
                        ans = judge.judge_single(ims, prompt_text)
                    else:
                        ans = judge.judge(packs[a], packs[b], prompt_text)
                    verdict = parse_verdict(ans)
                except Exception as e:
                    print(f"ERR {grid} {a}v{b}: {e}", flush=True)
                    continue
                rec = {"model": judge.name, "prompt": prompt_tag, "pack": args.pack,
                       "grid": grid, "a": a, "b": b,
                       "verdict": verdict, "raw": ans[-400:]}
                fout.write(json.dumps(rec) + "\n")
                fout.flush()
                print(f"{grid} {a} vs {b}: {verdict.get('overall') if verdict else 'PARSE_FAIL'}", flush=True)
    fout.close()


if __name__ == "__main__":
    main()
